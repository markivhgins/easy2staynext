async function seed() {
  console.log(`Connecting to MongoDB at: ${uri.replace(/\/\/[^@]+@/, '//***@')}`);
  const client = new MongoClient(uri);
  try {
    await client.connect();
    const db = client.db(dbName);
    const col = db.collection('listings');
    const defaultOwnerId = new ObjectId();
    const now = new Date();
    const validUntil = new Date(Date.now() + 90 * 864e5);
    const confirmedAt = new Date(Date.now() - 1 * 864e5);

    let upsertedCount = 0;
    for (const item of LISTINGS) {
      await col.updateOne(
        { slug: item.slug },
        {
          $setOnInsert: {
            _id: new ObjectId(),
            ownerId: defaultOwnerId,
            createdAt: now,
          },
          $set: {
            ...item,
            'verification.state': 'VERIFIED',
            'verification.validUntil': validUntil,
            'verification.verifiedAt': day(2),
            'verification.scope': 'Physical on-site audit & verified meter',
            'availability.status': 'AVAILABLE',
            'availability.confirmedAt': confirmedAt,
            updatedAt: now,
          },
        },
        { upsert: true }
      );
      upsertedCount++;
    }

    const total = await col.countDocuments();
    console.log(`✅ Successfully seeded/updated ${upsertedCount} listings into database '${dbName}'. Total in collection: ${total}`);
  } catch (err) {
    console.error('❌ Seeding error:', err.message);
  } finally {
    await client.close();
  }
}

seed();
